export function exercisesByModule(m: number): Exercise[] {
  return exercises.filter((e) => e.module === m);
}

export function exerciseById(id: string): Exercise | undefined {
  return exercises.find((e) => e.id === id);
}

export function quizPoolByTag(tag: QuizTag): Exercise[] {
  return exercises.filter((e) => e.tags.includes(tag) && e.quiz);
}
